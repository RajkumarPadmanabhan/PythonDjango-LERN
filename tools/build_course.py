"""Bundle lesson markdown into js/course-data.js.

Edit files in content/, then run:  python tools/build_course.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTENT = ROOT / "content"
OUT = ROOT / "js" / "course-data.js"

REQUIRED = ("id", "track", "level", "module", "title", "minutes", "summary")


def parse(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    if text.startswith("\ufeff"):
        text = text.lstrip("\ufeff")
    if not text.startswith("---"):
        raise SystemExit(f"missing front matter: {path}")
    parts = text.split("---", 2)
    if len(parts) < 3:
        raise SystemExit(f"front matter not closed: {path}")
    data: dict = {}
    for line in parts[1].strip().splitlines():
        if not line.strip():
            continue
        if ":" not in line:
            raise SystemExit(f"bad front-matter line in {path}: {line}")
        key, value = line.split(":", 1)
        data[key.strip()] = value.strip().strip('"')
    missing = [key for key in REQUIRED if key not in data]
    if missing:
        raise SystemExit(f"{path} missing {missing}")
    data["minutes"] = int(data["minutes"])
    data["keywords"] = [k.strip() for k in data.get("keywords", "").split(",") if k.strip()]
    data["md"] = parts[2].strip() + "\n"
    data["source"] = path.relative_to(ROOT).as_posix()
    return data


def main() -> None:
    lessons = [parse(path) for path in sorted(CONTENT.rglob("*.md"))]
    if not lessons:
        raise SystemExit(f"no lessons found in {CONTENT}")
    ids = [lesson["id"] for lesson in lessons]
    dupes = sorted({item for item in ids if ids.count(item) > 1})
    if dupes:
        raise SystemExit(f"duplicate lesson ids: {dupes}")
    payload = json.dumps(lessons, ensure_ascii=False, indent=2)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        "/* Generated by tools/build_course.py. Edit content/*.md, then rebuild. */\n"
        "window.PATHLINE_LESSONS = "
        + payload
        + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {len(lessons)} lessons -> {OUT}")


if __name__ == "__main__":
    try:
        main()
    except BrokenPipeError:
        sys.exit(0)
